#define OTA_ACK            0x06     /* ASCII "ACK" byte: never appears in the text messages */
#define OTA_RX_TIMEOUT_MS  10000u   /* wait for the header or a chunk after each ACK */

static void uart_print(const char *s)
{
    HAL_UART_Transmit(&huart1, (uint8_t *)s, (uint16_t)strlen(s), 500);
}

/* Drop a byte left in the receive register and clear an overrun, so the next
   receive starts with the first byte the host sends after our ACK. */
static void uart_flush_rx(void)
{
    while (__HAL_UART_GET_FLAG(&huart1, UART_FLAG_RXNE) || __HAL_UART_GET_FLAG(&huart1, UART_FLAG_ORE))
        (void)huart1.Instance->DR;
}

/* OTA stream read: called by bl_ota_run() for the 16-byte header and each data chunk.
   Sends ACK ("ready, send the next block") and waits for exactly len bytes from the HC-05. */
static int ota_read_uart(uint8_t *buf, uint32_t len)
{
    uint8_t ack = OTA_ACK;
    uart_flush_rx();
    HAL_UART_Transmit(&huart1, &ack, 1, 100);
    if (HAL_UART_Receive(&huart1, buf, (uint16_t)len, OTA_RX_TIMEOUT_MS) != HAL_OK)
        return -1;
    return 0;
}

/* One OTA attempt over the HC-05. Prints the result, returns a BL_OTA_* code. */
static int ota_attempt(void)
{
    bl_ota_ctx_t ctx;
    ota_stream_t stream = { .read = ota_read_uart, .set_total_size = NULL };
    char msg[32];

    int err = bl_ota_run(&ctx, &stream);
    if (err == BL_OTA_OK)
    {
        uart_print("OTA done\r\n");
    }
    else
    {
        snprintf(msg, sizeof(msg), "OTA failed, err=%d\r\n", err);
        uart_print(msg);
    }
    return err;
}

